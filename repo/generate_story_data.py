    phrases = act['phrases']
    dur = act['duration']
    total_len = sum(max(10, len(p)) for p in phrases)
    cues = []
    curr_t = 0.0
    for p in phrases:
        weight = max(10, len(p))
        p_dur = (weight / total_len) * dur
        start_t = round(curr_t, 2)
        end_t = round(curr_t + p_dur, 2)
        cues.append({'start': start_t, 'end': end_t, 'text': p})
        curr_t += p_dur
    if cues:
        cues[-1]['end'] = round(dur, 2)
    act['cues'] = cues
    del act['phrases']

