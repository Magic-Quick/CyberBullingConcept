        print(f"\nСоздание кинематографичной версии с фоновым эмбиентом: {cinematic_path}...")
        mix_cmd = [
            FFMPEG_PATH, "-y",
            "-i", master_voice_path,
            "-stream_loop", "-1", "-i", ambient_source,
            "-filter_complex",
            "[1:a]volume=0.10,afade=t=in:ss=0:d=3[ambient];"
            "[0:a]volume=1.0[voice];"
            "[voice][ambient]amix=inputs=2:duration=first:dropout_transition=2[out]",
            "-map", "[out]",
            "-b:a", "256k",
            cinematic_path
        ]
        subprocess.run(mix_cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        if os.path.exists(cinematic_path):
            print(f"Кинематографичная версия готова: {os.path.getsize(cinematic_path)} байт")

